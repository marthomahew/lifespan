/** Living in one of these countries (and not inside, where history waits at the gate). */
const inCountry =
  (...ids: string[]) =>
  (s: GameState): boolean =>
    ids.includes(s.player.country) && notInPrison(s);
const outside =
  (...ids: string[]) =>
  (s: GameState): boolean =>
    !ids.includes(s.player.country) && notInPrison(s);
/** Outcome odds: the child's view of a moment, or the grown-up's. */
