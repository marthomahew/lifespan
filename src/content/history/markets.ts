/** A value from an anchor table for a year: exact, or log-interpolated between anchors. */
const SORTED = new WeakMap<Record<number, number>, number[]>();
export function fromAnchors(table: Record<number, number>, year: number): number | null {
  let years = SORTED.get(table);
  if (!years) {
    years = Object.keys(table)
      .map(Number)
      .sort((a, b) => a - b);
    SORTED.set(table, years);
  }
  if (!years.length || year < (years[0] ?? 0) || year > (years.at(-1) ?? 0)) return null;
  if (table[year] !== undefined) return table[year] ?? null;
  const hi = years.find((y) => y > year) as number;
  const lo = [...years].reverse().find((y) => y < year) as number;
  const a = table[lo] as number;
  const b = table[hi] as number;
  const f = (year - lo) / (hi - lo);
  return Math.exp(Math.log(a) + (Math.log(b) - Math.log(a)) * f);
}
